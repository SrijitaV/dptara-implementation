
from dataclasses import dataclass
from typing import Optional


@dataclass
class Task:
    """
    Represents a computational task generated by an IoT device.
    """

    task_id: int
    size_mb: float
    original_priority: float
    arrival_time: float
    deadline: float
    task_type: str

    # Dynamic task information
    priority: Optional[float] = None

    # Resource allocation information
    assigned_resource: Optional[str] = None
    allocated_load: Optional[float] = None

    # Computational workload and CPU demand
    workload_mi: Optional[float] = None
    cpu_demand_mips: Optional[float] = None

    # Execution information
    start_time: Optional[float] = None
    completion_time: Optional[float] = None

    execution_time: float = 0.0
    energy_consumption: float = 0.0

    status: str = "pending"


@dataclass
class Resource:
    """
    Represents a local, edge, or cloud computing resource.
    """

    resource_id: str
    resource_type: str

    # CPU capacity and utilization (MIPS)
    capacity: float
    current_load: float = 0.0

    # Hardware characteristics
    processing_speed_mips: float = 0.0
    power_consumption_w: float = 0.0
    network_latency_ms: float = 0.0

    # Reliability and efficiency
    efficiency: float = 1.0
    downtime_rate: float = 0.0

    status: str = "active"

    @property
    def available_capacity(self):
        return max(
            0.0,
            self.capacity - self.current_load
        )

    @property
    def utilization(self):
        if self.capacity <= 0:
            return 0.0

        return self.current_load / self.capacity
